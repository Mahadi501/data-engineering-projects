with stg_payments as 
(
select 
PAYMENT_ID,
CLAIM_ID,
PAYMENT_DATE,
UPPER(PAYMENT_TYPE) AS PAYMENT_TYPE,
PAYMENT_AMOUNT,
PROVIDER_ID,
UPPER(PAYMENT_STATUS) AS PAYMENT_STATUS,
CREATED_TIMESTAMP,
SOURCE_FILE_NAME,
LOADED_AT_TIMESTAMP,
RECORD_LOADED_TIMESTAMP,
BATCH_ID,
SOURCE_SYSTEM 
from {{ source('bronze', 'PAYMENTS') }}
)
select * from stg_payments