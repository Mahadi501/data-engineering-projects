CREATE TABLE IF NOT EXISTS INSURANCE_DEV.BRONZE.PROVIDERS 
(
PROVIDER_ID VARCHAR(20),
PROVIDER_NAME VARCHAR(128),
PROVIDER_TYPE VARCHAR(50),
SPECIALITY VARCHAR(50),
REGION VARCHAR(50),
PROVIDER_STATUS VARCHAR(50),
SOURCE_FILE_NAME STRING,
LOADED_AT_TIMESTAMP DATETIME,
RECORD_LOADED_TIMESTAMP DATETIME,
BATCH_ID VARCHAR,
SOURCE_SYSTEM STRING
)
COMMENT = 'BRONZE TABLE TO LOAD PROVIDERS SOURCE DATA';


select distinct provider_id from INSURANCE_DEV.BRONZE.PROVIDERS;
