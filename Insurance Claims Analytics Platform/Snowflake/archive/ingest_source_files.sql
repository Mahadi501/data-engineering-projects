-- TASK TO INGEST CLAIMS SOURCE FILE
USE DATABASE INSURANCE_DEV;
USE SCHEMA BRONZE; 
CREATE TASK IF NOT EXISTS INGEST_CLAIMS_DATA 
WAREHOUSE = COMPUTE_WH,
SCHEDULE = 'USING CRON 0 9 * * * UTC' 
AS 
COPY INTO INSURANCE_DEV.BRONZE.CLAIMS
( 
    CLAIM_ID, 
    CLAIM_NUMBER, 
    WORKER_ID,
    EMPLOYER_ID,
    INJURY_CODE,
    INJURY_DATE,
    LODGEMENT_DATE,
    CLAIM_STATUS,
    CLAIM_TYPE,
    CLAIM_LIABILITY_STATUS, 
    CLAIM_MANAGER, 
    CREATED_TIMESTAMP, 
    UPDATED_TIMESTAMP, 
    SOURCE_FILE_NAME,
    LOADED_AT_TIMESTAMP,
    RECORD_LOADED_TIMESTAMP,
    BATCH_ID,
    SOURCE_SYSTEM
)
FROM 
    (
    SELECT 
            $1 AS CLAIM_ID,
            $2 AS CLAIM_NUMBER,
            $3 AS WORKER_ID,
            $4 AS EMPLOYER_ID,
            $5 AS INJURY_CODE,
            $6 AS INJURY_DATE,
            $7 AS LODGEMENT_DATE,
            $8 AS CLAIM_STATUS,
            $9 AS CLAIM_TYPE,
            $10 AS CLAIM_LIABILITY_STATUS,
            $11 AS CLAIM_MANAGER,
            $12 AS CREATED_TIMESTAMP,
            $13 AS UPDATED_TIMESTAMP,
            METADATA$FILENAME AS SOURCE_FILE_NAME,
            CURRENT_TIMESTAMP() AS LOADED_AT_TIMESTAMP,
            CURRENT_TIMESTAMP() AS RECORD_LOADED_TIMESTAMP,
            MD5(
            TO_VARCHAR(CURRENT_TIMESTAMP())
            ) AS BATCH_ID,
            'ACCTION' AS SOURCE_SYSTEM
    FROM @"INSURANCE_DEV"."BRONZE"."STAGE_RAW"/claims/
    )
PATTERN = '(?i).*\/claims.*\.csv$'
FILE_FORMAT = (FORMAT_NAME = CSV_FILES);




