CREATE OR REPLACE PROCEDURE INSURANCE_DEV.BRONZE.SP_INGEST_INJURY_REF_DATA(p_batch_id VARCHAR)
RETURNS VARIANT 
LANGUAGE SQL
AS
$$
DECLARE 
    V_FILE_NAME STRING;
    V_START_TIME TIMESTAMP_NTZ;
    V_END_TIME TIMESTAMP_NTZ;
    V_ROW_COUNT NUMBER(20,0);
    V_SQL_ID VARCHAR;
    V_STATUS STRING;
    V_COPY_RESULT VARIANT;

BEGIN
    V_START_TIME := CURRENT_TIMESTAMP();
    
    COPY INTO INSURANCE_DEV.BRONZE.INJURY_REFERENCE
    ( 
        INJURY_CODE,
        INJURY_DESCRIPTION,
        INJURY_CATEGORY,
        BODY_LOCATION,
        SEVERITY_CATEGORY,
        SOURCE_FILE_NAME,
        LOADED_AT_TIMESTAMP,
        RECORD_LOADED_TIMESTAMP,
        BATCH_ID,
        SOURCE_SYSTEM
    )
    FROM 
    (
    SELECT 
        $1 AS INJURY_CODE,
        $2 AS INJURY_DESCRIPTION,
        $3 AS INJURY_CATEGORY,
        $4 AS BODY_LOCATION,
        $5 AS SEVERITY_CATEGORY,
        METADATA$FILENAME AS SOURCE_FILE_NAME,
        :V_START_TIME AS LOADED_AT_TIMESTAMP,
        CURRENT_TIMESTAMP() AS RECORD_LOADED_TIMESTAMP,
        :p_batch_id AS BATCH_ID,
        'ACCTION' AS SOURCE_SYSTEM
    FROM  @"INSURANCE_DEV"."BRONZE"."STAGE_RAW"/injury_reference/
    )
    PATTERN = '(?i).*\/injury_reference.*\.csv$'
    FILE_FORMAT = (FORMAT_NAME = CSV_FILES);

    V_SQL_ID := SQLID;

    SELECT OBJECT_CONSTRUCT(*)
    INTO :V_COPY_RESULT
    FROM TABLE(RESULT_SCAN(:V_SQL_ID))
    LIMIT 1;

    V_FILE_NAME := GET_IGNORE_CASE(V_COPY_RESULT,'FILE');
    V_STATUS := GET_IGNORE_CASE(V_COPY_RESULT, 'STATUS')::STRING;
    V_ROW_COUNT := COALESCE(GET_IGNORE_CASE(V_COPY_RESULT, 'ROWS_LOADED')::NUMBER(20,0),0);

    V_END_TIME := CURRENT_TIMESTAMP();

    RETURN OBJECT_CONSTRUCT(
        'batch_id', p_batch_id,
        'file_name',V_FILE_NAME ,
        'start_time', V_START_TIME,
        'end_time', V_END_TIME,
        'row_count',V_ROW_COUNT,
        'status',V_STATUS,
        'target_table', 'INSURANCE_DEV.BRONZE.INJURY_REFERENCE'
    );    
END;
$$;

