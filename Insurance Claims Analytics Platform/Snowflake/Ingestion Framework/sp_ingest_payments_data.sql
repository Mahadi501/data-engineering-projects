CREATE OR REPLACE PROCEDURE INSURANCE_DEV.BRONZE.SP_INGEST_PAYMENTS_DATA(p_batch_id VARCHAR)
returns variant
language sql 
AS 
$$
DECLARE
    V_FILE_NAME STRING;
    V_START_TIME TIMESTAMP_NTZ;
    V_END_TIME TIMESTAMP_NTZ;
    V_ROW_COUNT NUMBER(20,0);
    V_SQL_ID VARCHAR;
    V_STATUS STRING;
    V_COPY_RESULT VARIANT;

BEGIN

    V_START_TIME := CURRENT_TIMESTAMP();

-- INGESTING PAYMENTS DATA FROM STAGE INTO THE BRONZE LAYER
COPY INTO INSURANCE_DEV.BRONZE.PAYMENTS 
( 
    PAYMENT_ID,
    CLAIM_ID,
    PAYMENT_DATE,
    PAYMENT_TYPE,
    PAYMENT_AMOUNT,
    PROVIDER_ID,
    PAYMENT_STATUS,
    CREATED_TIMESTAMP,
    SOURCE_FILE_NAME,
    LOADED_AT_TIMESTAMP,
    RECORD_LOADED_TIMESTAMP,
    BATCH_ID,
    SOURCE_SYSTEM
)
FROM 
    (
    SELECT 
            $1 AS PAYMENT_ID,
            $2 AS CLAIM_ID,
            $3 AS PAYMENT_DATE,
            $4 AS PAYMENT_TYPE,
            $5 AS PAYMENT_AMOUNT,
            $6 AS PROVIDER_ID,
            $7 AS PAYMENT_STATUS,
            $8 AS CREATED_TIMESTAMP,
            METADATA$FILENAME AS SOURCE_FILE_NAME,
            :V_START_TIME AS LOADED_AT_TIMESTAMP,
            CURRENT_TIMESTAMP() AS RECORD_LOADED_TIMESTAMP,
            :p_batch_id AS BATCH_ID,
            'ACCTION' AS SOURCE_SYSTEM
    FROM  @"INSURANCE_DEV"."BRONZE"."STAGE_RAW"/payments/
    )
PATTERN = '(?i).*\/claim_payments.*\.csv$'
FILE_FORMAT = (FORMAT_NAME = CSV_FILES);    

V_SQL_ID := SQLID;

-- EXTRACTING SOURCE FILE NAME AND ROW COUNT FROM QUERY RESULTS
SELECT OBJECT_CONSTRUCT(*)
INTO :V_COPY_RESULT
FROM TABLE(RESULT_SCAN(:V_SQL_ID))
LIMIT 1;

V_FILE_NAME := GET_IGNORE_CASE(V_COPY_RESULT,'FILE')::STRING;
V_STATUS := GET_IGNORE_CASE(V_COPY_RESULT,'STATUS')::STRING;
V_ROW_COUNT := COALESCE(GET_IGNORE_CASE(V_COPY_RESULT, 'ROWS_LOADED')::NUMBER(20,0),0);

V_END_TIME := CURRENT_TIMESTAMP();
    
RETURN object_construct(
        'batch_id', p_batch_id,
        'file_name',V_FILE_NAME ,
        'start_time', V_START_TIME,
        'end_time', V_END_TIME,
        'row_count',V_ROW_COUNT,
        'status',V_STATUS,
        'target_table', 'INSURANCE_DEV.BRONZE.PAYMENTS'
);
END;
$$;

