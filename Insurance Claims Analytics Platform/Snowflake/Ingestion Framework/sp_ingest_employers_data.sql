CREATE OR REPLACE PROCEDURE INSURANCE_DEV.BRONZE.SP_INGEST_EMPLOYERS_DATA(p_batch_id VARCHAR)
RETURNS VARIANT
LANGUAGE SQL
AS 
$$
DECLARE
    V_FILE_NAME STRING;
    V_START_TIME TIMESTAMP_NTZ;
    V_END_TIME TIMESTAMP_NTZ;
    V_ROW_COUNT NUMBER(20,0);
    V_SQL_ID VARCHAR;
    V_STATUS STRING;
    V_COPY_RESULT VARIANT;
BEGIN
    V_START_TIME := CURRENT_TIMESTAMP();

copy into insurance_dev.bronze.employers
( 
    EMPLOYER_ID,
    ABN,
    EMPLOYER_NAME,
    INDUSTRY,
    REGION,
    PREMIUM_SEGMENT,
    EMPLOYEE_COUNT,
    EFFECTIVE_DATE,
    LAST_UPDATED_DATE,
    SOURCE_FILE_NAME,
    LOADED_AT_TIMESTAMP,
    RECORD_LOADED_TIMESTAMP,
    BATCH_ID,
    SOURCE_SYSTEM
    )
FROM 
    (
    SELECT 
            $1 AS EMPLOYEE_ID,
            $2 AS ABN,
            $3 AS EMPLOYER_NAME,
            $4 AS INDUSTRY,
            $5 AS REGION,
            $6 AS PREMIUM_SEGMENT,
            $7 as EMPLOYEE_COUNT,
            $8 AS EFFECTIVE_DATE,
            $9 AS LAST_UPDATED_DATE,
            METADATA$FILENAME AS SOURCE_FILE_NAME,
            :V_START_TIME AS LOADED_AT_TIMESTAMP,
            CURRENT_TIMESTAMP() AS RECORD_LOADED_TIMESTAMP,
            :p_batch_id AS BATCH_ID,
            'ACCTION' AS SOURCE_SYSTEM
    FROM  @"INSURANCE_DEV"."BRONZE"."STAGE_RAW"/employers/
    )
PATTERN = '(?i).*\/employers.*\.csv$'
FILE_FORMAT = (FORMAT_NAME = CSV_FILES);

V_SQL_ID := SQLID;

-- extracting informations from the copy from stage commmand to store as variant type. 
SELECT OBJECT_CONSTRUCT(*)
INTO :V_COPY_RESULT
FROM TABLE(RESULT_SCAN(:V_SQL_ID))
LIMIT 1;

V_FILE_NAME := GET_IGNORE_CASE(V_COPY_RESULT,'FILE'):: STRING;
V_STATUS := GET_IGNORE_CASE(V_COPY_RESULT, 'STATUS')::STRING;
V_ROW_COUNT := COALESCE(GET_IGNORE_CASE(V_COPY_RESULT, 'ROWS_LOADED')::NUMBER(20,0),0);

V_END_TIME := CURRENT_TIMESTAMP();

return object_construct (
        'batch_id', p_batch_id,
        'file_name',V_FILE_NAME ,
        'start_time', V_START_TIME,
        'end_time', V_END_TIME,
        'row_count',V_ROW_COUNT,
        'status',V_STATUS,
        'target_table', 'INSURANCE_DEV.BRONZE.EMPLOYERS'
    );
END;
$$;


